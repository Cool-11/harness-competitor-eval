def build_task_md(tid, m, old: str) -> str:
    """按 cases/_template/task.md 的章节结构重排 task.md，保留原任务指令与完成条件。"""
    # 抽取原有内容
    instr = old.split("## 任务指令（原文，五款一字不差）")[1].split("## 投喂说明")[0].strip()
    comp = old.split("## 完成条件")[1].split("## 观察格位")[0].strip() if "## 完成条件" in old else ""
    # T00/T00b 结构不同，跳过重排
    return f"""# {tid} · {m['kind']} 用例

> 主测维度：{m['main']} ｜ 副测维度：{m['sub']} ｜ 运行次数：{m['runs']}

## 任务指令（原文，逐字投喂）

{instr}

## 投喂说明（评测者操作指引，不投喂给产品）

- **Codex / DSH**：把 `inputs/` 内全部文件放到工作目录，任务书原文粘贴
- **Workbuddy**：上传 `inputs/` 全部文件 + 任务书原文
- **元宝专家模式 / 豆包办公**：按产品原生方式上传 `inputs/` 全部文件 + 任务书原文
- **统一记录**：投喂时间、产品会话新建（禁止在旧会话中追加）、任务书 sha256 前 8 位

## 完成条件（checker 判定项）

{comp}

## 维度映射与设计意图

- **主测维度**：{m['main']}
- **副测维度**：{m['sub']}
- **为什么这题能区分**：{m['why']}

## 运行次数

{m['runs']}
"""


def build_spec_md(tid, m) -> str:
    rows = "\n".join(
        f"| {n} | {a} | {b} | {c} | {d} |" for n, a, b, c, d in m["anchors"]
    ) or "| （校准题不计分） | — | — | — | — |"
    return f"""# {tid} 题目规格（spec）

> 依据 docs/01 §5.2 四件套与 §7.1 行为分锚点（0–3 四级）。**本文件不投喂产品。**

## 质量关卡记录（每题过三关才入库，见 docs/01 §5.3）

| 关卡 | 内容 | 结果 | 日期 |
|---|---|---|---|
| 歧义审查 | 只读任务书能否读出两种都合理的解读 | ⬜ 待做 | |
| 难度分层 | 是否预期五款拉开差距 | ⬜ 待做 | |
| 裸模型探针 | 模型本身能做知识性部分吗 | ⬜ 待做 | |

## 判定锚点（行为分 0–3）

| 观察项 | 0 分 | 1 分 | 2 分 | 3 分 |
|---|---|---|---|---|
{rows}

## 运行次数

{m['runs']}

## 真值文件

同目录 `truth.json`（如存在）为 checker 读取的机读真值——**绝不进产品工作目录**。
"""


def main():
    for tid, m in META.items():
        d = next(p for p in CASES.iterdir() if p.is_dir() and p.name.startswith(tid + "-") or p.name == tid)
        t = d / "task.md"
        if tid in ("T00", "T00b"):
            # 校准题：仅补 spec.md
            (d / "spec.md").write_text(build_spec_md(tid, m), encoding="utf-8")
            print(f"  · {d.name}: spec.md")
            continue
        old = t.read_text(encoding="utf-8")
        t.write_text(build_task_md(tid, m, old), encoding="utf-8")
        (d / "spec.md").write_text(build_spec_md(tid, m), encoding="utf-8")
        # checker 上移到题根，真值改名 truth.json，CHECKSPEC 合并进 spec 后删除
        g = d / "grading"
        if g.exists():
            for py in g.glob("check_*.py"):
                shutil.move(str(py), str(d / "checker.py"))
            for gt in g.glob("_ground_truth*.json"):
                shutil.move(str(gt), str(d / "truth.json"))
            for cs in g.glob("CHECKSPEC.md"):
                extra = cs.read_text(encoding="utf-8")
                with (d / "spec.md").open("a", encoding="utf-8") as f:
                    f.write("\n---\n\n## checker 实现规格（原 CHECKSPEC）\n\n" + extra)
                cs.unlink()
            if not any(g.iterdir()):
                g.rmdir()
        print(f"  ✓ {d.name}: task.md + spec.md" + (" + checker.py" if (d / 'checker.py').exists() else ""))


if __name__ == "__main__":
    main()
